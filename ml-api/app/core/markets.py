def _round(x: float) -> int:  # JS Math.round 와 같게 (0.5 는 올림)
    return math.floor(x + 0.5)


def km(a: tuple[float, float], b: tuple[float, float]) -> int:
    r = math.pi / 180
    x = (b[1] - a[1]) * r * math.cos((a[0] + b[0]) / 2 * r)
    y = (b[0] - a[0]) * r
    return _round(math.sqrt(x * x + y * y) * 6371)


def markets_near(sido: str) -> list[tuple[Market, int]]:
    """시·도에서 가까운 도매시장 순서 [(시장, 거리 km)]"""
    c = SIDO_CENTER.get(sido, SIDO_CENTER["서울"])
    return sorted(((m, km(c, (m.lat, m.lon))) for m in MARKETS.values()), key=lambda t: t[1])


def _seeded(text: str) -> float:
    """frontend/src/utils/format.js seeded() 의 첫 값과 같은 고정 난수 (0~1)"""
    M = 0xFFFFFFFF
    h = 2166136261
    for ch in text:
        h = ((h ^ ord(ch)) * 16777619) & M
    h = ((h ^ (h >> 15)) * 2246822507) & M
    h = ((h ^ (h >> 13)) * 3266489909) & M
    h ^= h >> 16
    return (h & M) / 4294967296


def market_factor(crop: str, market: str | None) -> float:
    if not market or market == "national":
        return 1.0
    return 0.9 + _seeded(f"m|{crop}|{market}") * 0.2
